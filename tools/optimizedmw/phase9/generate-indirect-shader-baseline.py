"""Generate the separately reviewed indirect-draw PBR object recipe.

Exact Git objects and the checksum-pinned overlay are the input authorities.
Neither installed files nor asset/temporal certificates authorize this domain.
The whole object include/link closure is pinned, including inactive branches.
"""
import argparse
import base64
import hashlib
import importlib.util
import io
import json
from pathlib import Path
import re
import subprocess
import zipfile


def reviewed_payload(root):
    spec = importlib.util.spec_from_file_location('asset_baseline_inputs',
        root / 'tools/optimizedmw/phase9/generate-asset-shader-baseline.py')
    inputs = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(inputs)
    names = subprocess.check_output(['git', 'ls-tree', '-r', '--name-only',
        inputs.STOCK_REVISION, 'files/shaders'], cwd=root, text=True).splitlines()
    payload = {name[len('files/shaders/'):]: inputs.git_read(root, name)
        for name in names if Path(name).suffix in ('.glsl', '.vert', '.frag', '.geom', '.comp')
        and '/v3overlay/' not in name}
    overlay = base64.b64decode(b''.join(inputs.git_read(root,
        f'files/shaders/v3overlay/part{i:02}.b64')[:length]
        for i, length in enumerate(inputs.PART_LENGTHS)))
    if hashlib.sha256(overlay).hexdigest() != inputs.OVERLAY_SHA256:
        raise ValueError('Pinned PBR overlay checksum differs')
    with zipfile.ZipFile(io.BytesIO(overlay)) as archive:
        for entry in archive.infolist():
            if not entry.is_dir():
                payload[entry.filename] = archive.read(entry)
    closure = inputs.closure(payload)
    return inputs, {name: payload[name].replace(b'\r', b'') for name in sorted(closure)}


def reviewed_semantics(payload):
    # These are assertions about a fixed, separately reviewed recipe, never a
    # token-based permission for arbitrary shader files or future overlays.
    code = {name: re.sub(r'/\*.*?\*/|//[^\n]*', '', raw.decode(), flags=re.S)
        for name, raw in payload.items()}
    forbidden = re.compile(r'\b(?:atomic\w*|image(?:Load|Store|Atomic)\w*|memoryBarrier\w*|barrier|'
        r'EmitVertex|EndPrimitive|gl_(?:DrawID\w*|BaseInstance\w*|VertexID|InstanceID|PrimitiveID\w*|'
        r'InvocationID|FragDepth))\b')
    for name, source in code.items():
        if forbidden.search(source):
            raise ValueError('Unreviewed command boundary / side effect: ' + name)
        if re.search(r'\bgl_Position\s*(?:[+*/-]?=|\+\+|--)', source) and name != 'compatibility/objects.vert':
            raise ValueError('Unexpected clip-position producer: ' + name)
        # The lighting declarations are shared with compute code, but these
        # object vertex/fragment consumers only read their storage resources.
        if re.search(r'\b(?:clusters|pointLight|lightGrid|lightIndexList|globalLightIndexCount)'
                r'\s*(?:\[[^\]]*\])?\s*(?:\.[A-Za-z_]+)?\s*(?:[+*/-]?=|\+\+|--)', source):
            raise ValueError('Object lighting storage write: ' + name)
    object_source = code['compatibility/objects.vert']
    if len(re.findall(r'\bgl_Position\s*=', object_source)) != 1 or \
            'gl_Position = modelToClip(gl_Vertex);' not in object_source:
        raise ValueError('Object linear projection producer differs')
    core = code['lib/core/vertex.glsl']
    if 'return projectionMatrix * modelToView(pos);' not in core or \
            'return gl_ModelViewMatrix * pos;' not in core:
        raise ValueError('Mono object projection recipe differs')


def generate(root):
    inputs, payload = reviewed_payload(root)
    reviewed_semantics(payload)
    header = ['// Generated by generate-indirect-shader-baseline.py; indirect domain only.',
        '// Exact stock Git object: ' + inputs.STOCK_REVISION,
        '// Exact PBR overlay SHA256: ' + inputs.OVERLAY_SHA256,
        '#ifndef OPENMW_SHADER_INDIRECTPROJECTIONPBRBASELINE_H',
        '#define OPENMW_SHADER_INDIRECTPROJECTIONPBRBASELINE_H', '#include <string_view>',
        'namespace Shader::IndirectProjection {',
        'inline bool pbrBaselineRaw(std::string_view name, std::string_view source) {',
        'std::string_view expected;']
    for name, raw in payload.items():
        header.append('if (name == ' + json.dumps(name) + ') expected =')
        header.extend(json.dumps(line) for line in raw.decode().splitlines(keepends=True))
        header.append(';')
    header.extend(['if (expected.empty()) return false;', 'std::size_t i = 0;',
        "for (char c : source) { if (c == '\\r') continue; if (i == expected.size() || expected[i++] != c) return false; }",
        'return i == expected.size();', '}', '}', '#endif', ''])
    inventory = {'schema': 1, 'domain': 'indirect-command-repacking-and-linear-mono-object-projection',
        'stock_revision': inputs.STOCK_REVISION, 'overlay_sha256': inputs.OVERLAY_SHA256,
        'roots': inputs.ROOTS, 'include_and_all_link_branches': True,
        'review': {'linear_undeformed_positions': True, 'draw_boundary_observers': False,
            'object_storage_writes': False, 'lighting_storage_reads_preserved': True,
            'vertex_parameters_require_numeric_recipe': True,
            'multiview_requires_separate_review': True,
            'asset_or_temporal_certificate_is_indirect_authority': False},
        'records': [{'path': name, 'sha256': hashlib.sha256(raw).hexdigest()}
            for name, raw in payload.items()]}
    return '\n'.join(header).encode(), (json.dumps(inventory, indent=2) + '\n').encode(), payload


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--fixture-dir', type=Path,
        help='Materialize the exact reviewed object closure for production ShaderManager tests')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[3]
    header, inventory, payload = generate(root)
    for name, data in {'components/shader/indirectprojectionpbrbaseline.hpp': header,
            'components/shader/indirectprojectionpbrbaseline.inputs.json': inventory}.items():
        target = root / name
        if args.check:
            if not target.is_file() or target.read_bytes() != data:
                raise ValueError('Reviewed generated indirect baseline differs: ' + name)
        else:
            target.write_bytes(data)
    if args.fixture_dir:
        for name, data in payload.items():
            target = args.fixture_dir / name
            if target.exists() and target.read_bytes() != data:
                raise ValueError('Preserve existing different fixture input: ' + str(target))
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
    print('INDIRECT_SHADER_BASELINE_PASS exact_pbr=1 numeric_recipe_required=1 installed_authority=0')


if __name__ == '__main__':
    main()
