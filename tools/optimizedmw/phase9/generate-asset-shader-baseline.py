"""Generate the reviewed asset-only stock / composed PBR raw dependency pins.

Inputs are exact Git objects plus the existing checksum-pinned overlay archive.
Installed files, package manifests and mutable working shader files are never
an authority for generating a certificate. Run --check in validation.
"""
import argparse
import base64
import hashlib
import io
import json
from pathlib import Path, PurePosixPath
import re
import subprocess
import zipfile

STOCK_REVISION = '52761bedc0f369bd37ceb17eaeaf53701f2ed551'
OVERLAY_SHA256 = '6f42a686e2a6a9038bbd4a9e2d0d1be6d8812b9b3e681d8b569560c2fe110255'
PART_LENGTHS = [8000] * 7 + [4992]
ROOTS = ['compatibility/objects.vert', 'compatibility/objects.frag']
REFERENCE = re.compile(r'(?:#include|@link)\s+"([^"]+)"')


def digest(data):
    # Matches ShaderManager's Windows text-mode input and baselineRaw CR rule.
    return hashlib.sha256(data.replace(b'\r', b'')).hexdigest()


def git_read(root, name):
    return subprocess.check_output(['git', 'show', STOCK_REVISION + ':' + name], cwd=root)


def closure(payload):
    pending, seen = list(ROOTS), {}
    while pending:
        name = pending.pop()
        if name in seen:
            continue
        if name not in payload or len(seen) >= 128:
            raise ValueError('Missing / unbounded reviewed dependency: ' + name)
        raw = payload[name]
        seen[name] = digest(raw)
        for target in REFERENCE.findall(raw.decode('utf-8')):
            if not target.startswith(('lib', 'compatibility', 'core')):
                target = str(PurePosixPath(name).parent / target)
            if '..' in PurePosixPath(target).parts or PurePosixPath(target).is_absolute():
                raise ValueError('Unreviewed dependency traversal: ' + target)
            pending.append(target)
    return seen


def generate(root):
    names = subprocess.check_output(['git', 'ls-tree', '-r', '--name-only', STOCK_REVISION,
        'files/shaders'], cwd=root, text=True).splitlines()
    stock = {name[len('files/shaders/'):]: git_read(root, name) for name in names
        if Path(name).suffix in ('.glsl', '.vert', '.frag', '.geom', '.comp')
        and '/v3overlay/' not in name}
    parts = [git_read(root, f'files/shaders/v3overlay/part{i:02}.b64')[:length]
        for i, length in enumerate(PART_LENGTHS)]
    overlay = base64.b64decode(b''.join(parts))
    if hashlib.sha256(overlay).hexdigest() != OVERLAY_SHA256:
        raise ValueError('Reviewed overlay archive does not match fixed SHA256')
    pbr = dict(stock)
    with zipfile.ZipFile(io.BytesIO(overlay)) as archive:
        for item in archive.infolist():
            if not item.is_dir():
                pbr[item.filename] = archive.read(item)
    families = {'stock': closure(stock), 'pbr': closure(pbr)}
    records = []
    for name in sorted(set(families['stock']) | set(families['pbr'])):
        records.append({'path': name, 'stock': families['stock'].get(name, ''),
            'pbr': families['pbr'].get(name, '')})
    header = ['// Generated by generate-asset-shader-baseline.py; reviewed asset-only recipes.',
        '// Stock Git object: ' + STOCK_REVISION, '// Composed PBR overlay SHA256: ' + OVERLAY_SHA256,
        '#ifndef OPENMW_SHADER_ASSETGEOMETRYBASELINE_H', '#define OPENMW_SHADER_ASSETGEOMETRYBASELINE_H',
        '#include <string_view>', 'namespace Shader::AssetGeometry::Baseline {',
        'struct RawEntry { std::string_view path, stock, pbr; };',
        'inline constexpr RawEntry entries[] = {']
    for record in records:
        header.append('    { ' + ', '.join(json.dumps(record[k]) for k in ('path', 'stock', 'pbr')) + ' },')
    header.extend(['};', '}', '#endif', ''])
    inventory = {'schema': 1, 'stock_revision': STOCK_REVISION, 'overlay_sha256': OVERLAY_SHA256,
        'roots': ROOTS, 'include_and_all_link_branches': True, 'records': records}
    return '\n'.join(header).encode(), (json.dumps(inventory, indent=2) + '\n').encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[3]
    header, inventory = generate(root)
    outputs = {'components/shader/assetgeometrybaseline.hpp': header,
        'components/shader/assetgeometrybaseline.inputs.json': inventory}
    for name, data in outputs.items():
        target = root / name
        if args.check:
            if not target.is_file() or target.read_bytes() != data:
                raise ValueError('Reviewed generated asset baseline differs: ' + name)
        else:
            target.write_bytes(data)
    print('ASSET_SHADER_BASELINE_PASS stock_and_pbr=1 pinned_overlay=1 installed_authority=0')


if __name__ == '__main__':
    main()
